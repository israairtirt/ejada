  var STORAGE_KEY = "ejada-lang";
  var lang = "en";
  var fromUrl = (location.search.match(/[?&]lang=(ar|en)/) || [])[1];
  try { if ((fromUrl || localStorage.getItem(STORAGE_KEY)) === "ar") lang = "ar"; } catch (e) { if (fromUrl === "ar") lang = "ar"; }

  function apply(root) {
    if (lang !== "ar") return;
    var nodes = (root || document).querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var v = AR[nodes[i].getAttribute("data-i18n")];
      if (v != null) nodes[i].innerHTML = v;
    }
  }

  function setLang(next) {
    try { localStorage.setItem(STORAGE_KEY, next); } catch (e) {}
    // A reload keeps layout-dependent animations (split text, scroll triggers, marquee direction) correct.
    location.reload();
  }

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  if (lang === "ar") {
    var page = document.body.getAttribute("data-page");
    if (AR["title." + page]) document.title = AR["title." + page];
    apply(document);
  }

  window.I18N = {
    lang: lang,
    apply: apply,
    set: setLang,
    t: function (key, fallback) { return lang === "ar" && AR[key] != null ? AR[key] : fallback; }
  };
